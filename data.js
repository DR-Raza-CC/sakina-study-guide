// Teaching order: week by week. A word that appears again in a later week
// (review weeks) is taught once and then comes back through daily reviews.
window.buildWordOrder = function () {
  var order = [], seen = {};
  window.SPELLING_WEEKS.forEach(function (wk) {
    wk.words.forEach(function (w) {
      var k = w[0].toLowerCase();
      if (seen[k]) return;
      seen[k] = 1;
      order.push({ word: w[0], sentence: w[1], unit: wk.id });
    });
  });
  return order;
};

window.UNIT_INFO = (function () {
  var m = { tricky: { title: "Tricky words", tip: "Look at the tricky bit, say it in a funny way, and practise!" },
            school: { title: "This week's school spellings", tip: "These are the words from your homework this week. Let's practise them!" } };
  window.SPELLING_WEEKS.forEach(function (wk) {
    m[wk.id] = { title: wk.term + " · Week " + wk.week + ": " + wk.title, tip: wk.tip };
  });
  return m;
})();
