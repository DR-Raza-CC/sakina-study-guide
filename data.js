// Teaching order: each rule unit, followed by 5 tricky words.
window.buildWordOrder = function () {
  var order = [];
  var t = 0;
  window.SPELLING_UNITS.forEach(function (u) {
    u.words.forEach(function (w) { order.push({ word: w[0], sentence: w[1], unit: u.id }); });
    for (var i = 0; i < 5 && t < window.TRICKY_WORDS.length; i++, t++) {
      var tw = window.TRICKY_WORDS[t];
      order.push({ word: tw[0], sentence: tw[1], unit: "tricky" });
    }
  });
  while (t < window.TRICKY_WORDS.length) {
    var w2 = window.TRICKY_WORDS[t++];
    order.push({ word: w2[0], sentence: w2[1], unit: "tricky" });
  }
  return order;
};

